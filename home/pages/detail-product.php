                        <h1 style="width: 100%; text-align: center;">Product Details</h1>
                        <p>Representing a dramatic leap forward in power and connectivity within a
                            remarkably compact format, Quantum 338
                            follows the Quantum 7 in defining the future of audio mixing.</p>
                        <p>Boasting a wealth of new design features and enhancements to create ultimate
                            flexibility of use plus the speed of
                            operation that only Quantum can deliver, Quantum 338 is based on seventh
                            generation FPGAs with an entirely new
                            system architecture. The console merges tried and tested workflows with immense
                            processing muscle and bold
                            innovation including a striking new dark mode.</p>
                        <p>Quantum 338 puts a trio of 17-inch, 1000 nit, high brightness multitouch screens
                            at your disposal, with both the
                            meter bridge and soft quick select buttons displayed on each screen for quick,
                            intuitive operation. In addition, 70
                            individual TFT channel displays join the floating Quantum chassis with 38 100mm
                            touch sensitive faders laid out in
                            three blocks of 12 fader banks plus two dedicated user-assignable faders, each
                            with high resolution metering.</p>
                        <p>Superior local audio connectivity and performance comes courtesy of new “Ultimate
                            Stadius” 32-bit ADC and DAC
                            conversion, which is built into the Quantum 338 as standard alongside six single
                            or three redundant MADI
                            connections, dual DMI slots and a built-in UB MADI USB recording interface.</p>
                        <p>Also included as standard are Mustard Processing channel strips, Spice Rack
                            plugin style native FPGA processing
                            options, Nodal Processing and True Solo.</p>
                        <p>With a maximum of 128 input channels with 64 busses and a 24 x 24 matrix, all
                            with full channel processing, Quantum
                            338 takes built-in console I/O to new levels of performance.</p>
                        <p>The console’s 8 local mic/line inputs and eight local line outputs all feature
                            32-bit “Ultimate Stadius” converters,
                            while users have access to 4 stereo AES/EBU in/out, triple redundant MADI in/out
                            (which can also be configured as 6
                            MADI I/O at 48kHz), dual DMI card slots, support for dual second generation
                            Optocore loops, a built-in UB MADI USB
                            interface and more. Waves connectivity can also be added with a SoundGrid
                            Interface card, adding up to an additional
                            64 I/O.</p>
